import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

/**
 * Where the bytes live.
 *
 * Deliberately an interface with a local implementation behind it, in the same
 * spirit as the no-op event publisher: MinIO is already in docker-compose, and
 * an S3 implementation slots in here without a single call site changing. What
 * matters for the platform's claim is not where the bytes sit but that nobody
 * reaches them without the database agreeing first — and that decision happens
 * before any store method below is ever called.
 */
export interface ObjectStore {
  put(key: string, body: Buffer): Promise<void>;
  get(key: string): Promise<Buffer | undefined>;
  delete(key: string): Promise<void>;
}

/**
 * A storage key that reveals nothing.
 *
 * Not derived from the bucket or the object name: a key that embedded them
 * would leak the tenant's filenames to anyone who could list the underlying
 * bucket, which is precisely the audience the platform does not trust.
 */
export function newStorageKey(projectId: string): string {
  const shard = createHash('sha256').update(projectId).digest('hex').slice(0, 8);
  return `${shard}/${randomUUID()}`;
}

/** In-memory store. Used by tests, and by nothing else. */
export function createMemoryStore(): ObjectStore {
  const objects = new Map<string, Buffer>();
  return {
    async put(key, body) {
      objects.set(key, body);
    },
    async get(key) {
      return objects.get(key);
    },
    async delete(key) {
      objects.delete(key);
    },
  };
}

/**
 * Filesystem store, rooted at STORAGE_ROOT.
 *
 * Keys are generated by newStorageKey and never taken from a request, but the
 * containment check below runs anyway — a key that escaped the root would be a
 * path traversal, and this is the last place to notice.
 */
export function createFilesystemStore(root: string): ObjectStore {
  const base = resolve(root);

  const pathFor = (key: string): string => {
    const full = resolve(join(base, key));
    if (full !== base && !full.startsWith(base + sep())) {
      throw new Error('storage key escapes the storage root');
    }
    return full;
  };

  return {
    async put(key, body) {
      const path = pathFor(key);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, body);
    },
    async get(key) {
      try {
        return await readFile(pathFor(key));
      } catch {
        return undefined;
      }
    },
    async delete(key) {
      await rm(pathFor(key), { force: true });
    },
  };
}

function sep(): string {
  return process.platform === 'win32' ? '\\' : '/';
}

export function createStoreFromEnv(): ObjectStore {
  return createFilesystemStore(process.env.STORAGE_ROOT ?? join(process.cwd(), '.storage'));
}
